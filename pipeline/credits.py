#!/usr/bin/env python3
"""Credits (T-208): CREDITS.md and the in-level credits, built from the data source manifests.

    uv run --no-project --python 3.12 python pipeline/credits.py
        # lists every source with its attribution line, rewrites the generated block of CREDITS.md,
        # and writes the in-level credits to H:/BelfastData/credits (credits.txt, info_credit.txt)

Inputs:
  * every data/sources/*.json is one data source (new manifests need no code change).
  * STATIC_SOURCES below: non-data sources (MapNG, BeamNG assets, reference-only projects, Mapillary).

Attribution lines for a manifest, in this order, de-duplicated:
  1. `credits_required` (list of strings), 2. top-level `attribution_text` or `attribution`,
  3. each file's `attribution_text`. If none of those exist, the licence fields are used instead
  (top-level `licence`, else each file's `licence`). A manifest with no attribution and no licence
  field is an error (ManifestError), and the run stops without writing anything.

CREDITS.md: the text between the two BEGIN/END marker lines is generated. Hand-written text outside the
markers is kept as it is. If the markers are missing, the block is appended at the end.

In-level credits: `write_level_credits(level_dir)` copies credits.txt into a level folder and returns the
one-line credit string for info.json (the export step appends it to `description`). See docs/credits.md.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCES_DIR = ROOT / "data" / "sources"
CREDITS_MD = ROOT / "CREDITS.md"
DEFAULT_OUT_DIR = Path("H:/BelfastData/credits")

BEGIN = "<!-- credits:begin (generated by pipeline/credits.py from data/sources; do not edit) -->"
END = "<!-- credits:end -->"

# Non-data sources. `in_level` puts the line in the level's credits (things the level uses).
STATIC_SOURCES = [
    {
        "id": "mapng",
        "in_level": True,
        "attribution": "MapNG by Nikki Luzader, MIT licence, Copyright (c) 2026 Nikki Luzader. "
                       "Level generator, used at a pinned commit (third_party/mapng).",
    },
    {
        "id": "beamng_assets",
        "in_level": True,
        "attribution": "BeamNG.drive stock assets (road signs, shapes, materials) are referenced from the game, "
                       "not copied. BeamNG GmbH, used under the game's EULA.",
    },
    {
        "id": "beamng_earth_ref",
        "in_level": False,
        "attribution": "BeamNG.Earth (MIT): reference only, engine measurements and UK marking dimensions. "
                       "No code copied.",
    },
    {
        "id": "earthng_ref",
        "in_level": False,
        "attribution": "EarthNG: reference only, road-audit ideas. No code copied.",
    },
    {
        "id": "mapillary",
        "in_level": False,
        "attribution": "Mapillary street photos (CC BY-SA 4.0) are used as evidence for road fixes. "
                       "Images are never committed.",
    },
]


class ManifestError(ValueError):
    """A data source manifest that cannot give an attribution line."""


def _strings(value) -> list[str]:
    if isinstance(value, str):
        return [value]
    if isinstance(value, list):
        return [v for v in value if isinstance(v, str)]
    return []


def _dedupe(items: list[str]) -> list[str]:
    out, seen = [], set()
    for item in items:
        text = " ".join(item.split())
        if text and text not in seen:
            seen.add(text)
            out.append(text)
    return out


def manifest_lines(path: Path, data: dict) -> list[str]:
    """Attribution lines for one manifest. Raises ManifestError if it has no attribution or licence."""
    if not isinstance(data, dict):
        raise ManifestError(f"{path.name}: top level must be a JSON object")
    files = [f for f in data.get("files", []) if isinstance(f, dict)]
    lines = _strings(data.get("credits_required"))
    lines += _strings(data.get("attribution_text")) + _strings(data.get("attribution"))
    lines += [t for f in files for t in _strings(f.get("attribution_text"))]
    lines = _dedupe(lines)
    if not lines:
        lines = _dedupe(_strings(data.get("licence")) or [t for f in files for t in _strings(f.get("licence"))])
    if not lines:
        raise ManifestError(f"{path.name}: no attribution or licence field, so no credit line can be made")
    return lines


def load_sources(sources_dir: Path = SOURCES_DIR) -> list[dict]:
    """[{id, lines, in_level}] for every manifest, then the static sources. Raises ManifestError."""
    sources = []
    for path in sorted(sources_dir.glob("*.json")):
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as exc:
            raise ManifestError(f"{path.name}: cannot read manifest ({exc})") from exc
        sources.append({"id": path.stem, "lines": manifest_lines(path, data), "in_level": True})
    for item in STATIC_SOURCES:
        sources.append({"id": item["id"], "lines": [item["attribution"]], "in_level": item["in_level"]})
    return sources


def render_block(sources: list[dict]) -> str:
    out = [BEGIN, "", "Every data source used by the project, with the attribution it requires. Generated from",
           "`data/sources/*.json` and the static list in `pipeline/credits.py`.", ""]
    out.append("## Attribution lines")
    out.append("")
    for src in sources:
        out.append(f"### {src['id']}")
        out.append("")
        out += [f"- {line}" for line in src["lines"]]
        out.append("")
    out.append(END)
    return "\n".join(out)


def update_credits_md(path: Path, block: str) -> None:
    text = path.read_text(encoding="utf-8") if path.exists() else "# Credits and licences\n"
    if BEGIN in text and END in text:
        head, rest = text.split(BEGIN, 1)
        tail = rest.split(END, 1)[1]
        new = head + block + tail
    else:
        new = text.rstrip() + "\n\n" + block + "\n"
    path.write_text(new, encoding="utf-8", newline="\n")


def level_credit_text(sources: list[dict]) -> str:
    lines = ["Belfast map credits", ""]
    for src in sources:
        if src["in_level"]:
            lines += src["lines"]
    return "\n".join(lines) + "\n"


def info_credit_string(sources: list[dict]) -> str:
    """One line for info.json `description`."""
    parts = [line for src in sources if src["in_level"] for line in src["lines"]]
    return "Credits: " + "; ".join(parts)


def write_level_credits(level_dir: Path, sources_dir: Path = SOURCES_DIR) -> str:
    """Copy the in-level credits text into a level folder and return the info.json credit string."""
    sources = load_sources(sources_dir)
    level_dir = Path(level_dir)
    level_dir.mkdir(parents=True, exist_ok=True)
    (level_dir / "credits.txt").write_text(level_credit_text(sources), encoding="utf-8", newline="\n")
    return info_credit_string(sources)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--sources-dir", type=Path, default=SOURCES_DIR)
    ap.add_argument("--credits-md", type=Path, default=CREDITS_MD)
    ap.add_argument("--out-dir", type=Path, default=DEFAULT_OUT_DIR)
    ap.add_argument("--no-write", action="store_true", help="list only; write nothing")
    args = ap.parse_args(argv)
    try:
        sources = load_sources(args.sources_dir)
    except ManifestError as exc:
        print(f"FAIL: {exc}", file=sys.stderr)
        return 2
    for src in sources:
        for line in src["lines"]:
            print(f"{src['id']}: {line}")
    if args.no_write:
        return 0
    update_credits_md(args.credits_md, render_block(sources))
    args.out_dir.mkdir(parents=True, exist_ok=True)
    (args.out_dir / "credits.txt").write_text(level_credit_text(sources), encoding="utf-8", newline="\n")
    (args.out_dir / "info_credit.txt").write_text(info_credit_string(sources) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {args.credits_md}")
    print(f"wrote {args.out_dir / 'credits.txt'} and info_credit.txt")
    return 0


if __name__ == "__main__":
    sys.exit(main())
